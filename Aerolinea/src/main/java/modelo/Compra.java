package modelo;

import java.sql.Date;

/**
 *
 * @author JORGE
 */
public class Compra {
    int id;
    Date fecha;

    public Compra(int id, Date fecha) {
        this.id = id;
        this.fecha = fecha;
    }
    
    public Compra(Date fecha) {
        this.fecha = fecha;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public Date getFecha() {
        return fecha;
    }

    public void setFecha(Date fecha) {
        this.fecha = fecha;
    }
    
    
}
